"""Draft assembly: validate the model's texts, fall back when they
can't be validated, and render the final commit message + changelog.

Honesty rule: a model text is used only if it passes deterministic
validation. Anything that falls back is LABELED as fallback in the
rendered output. The commit body (file stats) is always generated by
code — the model never writes numbers.
"""

import re

from .digest import fallback_bullets, fallback_subject, totals

MAX_SUBJECT_LEN = 100
MAX_BULLETS = 6
MAX_BULLET_LEN = 140

_SUBJECT_RE = re.compile(
    r"^(feat|fix|docs|style|refactor|perf|test|build|ci|chore|revert)"
    r"(\([a-z0-9][a-z0-9_/.\-]*\))?"
    r":\s+(\S.*)$"
)

_SCOPE_RE = re.compile(r"^[a-z]+\(([^)]+)\)")


def subject_grounded(subject, files):
    """Check that a subject's scope is grounded in the actual diff.

    A tiny model sometimes parrots the one-shot example's scope (an
    early DiffScribe run produced 'feat(auth): …' for a diff with no
    auth code anywhere). If the subject names a scope, that scope must
    appear in at least one changed file's path or signal lines —
    otherwise the subject is treated as unusable and the caller falls
    back. Scopeless subjects are always grounded. Substring matching is
    a heuristic (scope 'auth' would match a path containing 'author');
    it exists to catch wholesale example leakage, not to prove relevance.
    """
    m = _SCOPE_RE.match(subject)
    if not m:
        return True
    scope = m.group(1).lower()
    for f in files:
        if scope in f.path.lower():
            return True
        if any(scope in s.lower() for s in f.signals):
            return True
    return False


def parse_subject(reply):
    """Validate one model reply as a conventional-commit subject.

    Returns the normalized subject line, or None if the reply is not a
    single, well-formed subject (caller must fall back). Only the first
    non-empty line is considered; anything chattier is rejected so the
    failure is visible rather than silently trimmed into shape.
    """
    lines = [ln.strip() for ln in reply.strip().splitlines() if ln.strip()]
    if len(lines) != 1:
        return None
    line = lines[0].strip("`").strip()
    m = _SUBJECT_RE.match(line)
    if not m:
        return None
    summary = m.group(3).strip()
    if len(summary) < 3 or line.endswith("."):
        return None
    if len(line) > MAX_SUBJECT_LEN:
        return None
    return line


def parse_bullets(reply):
    """Validate one model reply as changelog bullets.

    Returns a list of normalized '- …' bullets (1..MAX_BULLETS), or None
    if the reply contains no usable bullet lines (caller must fall back).
    Non-bullet lines are ignored only if at least one clean bullet
    exists; overlong bullets are rejected, not truncated.
    """
    bullets = []
    for ln in reply.strip().splitlines():
        ln = ln.strip()
        if ln.startswith("- ") or ln.startswith("* "):
            text = ln[2:].strip()
            if not text or len(text) > MAX_BULLET_LEN:
                return None
            bullets.append(f"- {text}")
    if not bullets or len(bullets) > MAX_BULLETS:
        return None
    return bullets


class Draft:
    """The assembled draft: validated texts + provenance flags."""

    def __init__(self, subject, subject_fallback, bullets, bullets_fallback,
                 files):
        self.subject = subject
        self.subject_fallback = subject_fallback
        self.bullets = bullets
        self.bullets_fallback = bullets_fallback
        self.files = files

    def body_lines(self):
        """Deterministic commit body: exact stats, always from code."""
        n, added, deleted = totals(self.files)
        lines = [f"Files changed: {n} (+{added} -{deleted})"]
        for f in self.files:
            lines.append(f"- {f.path}: {f.totals_line()} ({f.kind})")
        return lines


def assemble(files, subject_reply=None, bullets_reply=None):
    """Build a Draft from raw model replies (or None when unavailable).

    subject_reply / bullets_reply are the model's raw texts; each is
    validated independently and falls back independently, so a bad
    subject never contaminates good bullets and vice versa.
    """
    subject = parse_subject(subject_reply) if subject_reply else None
    if subject is not None and not subject_grounded(subject, files):
        subject = None  # well-formed but not about this diff — fall back
    subject_fallback = subject is None
    if subject_fallback:
        subject = fallback_subject(files)
    bullets = parse_bullets(bullets_reply) if bullets_reply else None
    bullets_fallback = bullets is None
    if bullets_fallback:
        bullets = fallback_bullets(files)
    return Draft(subject, subject_fallback, bullets, bullets_fallback, files)


def render(draft, method_note, label_fallbacks=True):
    """Render the draft into human-readable text.

    label_fallbacks=False is used in --no-llm mode, where the method
    note already says no model was run — claiming a model text "could
    not be used" there would be misleading.
    """
    lines = [
        "=== DIFFSCRIBE draft ===",
        f"method: {method_note}",
        "",
        "COMMIT MESSAGE:",
        draft.subject,
    ]
    if label_fallbacks and draft.subject_fallback:
        lines.append(
            "(subject drafted by the deterministic fallback — the model's "
            "subject could not be used)")
    lines.append("")
    lines.extend(draft.body_lines())
    lines += ["", "CHANGELOG ENTRY (Unreleased):"]
    lines.extend(draft.bullets)
    if label_fallbacks and draft.bullets_fallback:
        lines.append(
            "(bullets drafted by the deterministic fallback — the "
            "model's bullets could not be used)")
    lines += ["",
              "Every number above was counted from the diff by code. "
              "The model only worded the texts marked as its own."]
    return "\n".join(lines)
